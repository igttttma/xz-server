package xiaozhi.common.utils;

import static org.junit.jupiter.api.Assertions.assertEquals;

import org.junit.jupiter.api.Test;

public class AESUtilsTest {

    @Test
    public void testEncryptAndDecrypt() {
        String key = "xiaozhi1234567890";
        String plainText = "Hello, XiaoZhi!";

        System.out.println("Plain text: " + plainText);
        System.out.println("Key: " + key);

        // Encrypt
        String encrypted = AESUtils.encrypt(key, plainText);
        System.out.println("Encrypted result: " + encrypted);

        // Decrypt
        String decrypted = AESUtils.decrypt(key, encrypted);
        System.out.println("Decrypted result: " + decrypted);

        // Verify
        assertEquals(plainText, decrypted, "Encryption and decryption results should match");
        System.out.println("Encryption/decryption consistency: " + plainText.equals(decrypted));
    }

    @Test
    public void testDifferentKeyLengths() {
        String[] keys = {
                "1234567890123456", // 16 characters
                "123456789012345678901234", // 24 characters
                "12345678901234567890123456789012", // 32 characters
                "short", // Short key
                "verylongkeythatwillbetruncatedto32bytes" // Long key
        };

        String plainText = "test text";

        for (String key : keys) {
            String encrypted = AESUtils.encrypt(key, plainText);
            String decrypted = AESUtils.decrypt(key, encrypted);
            assertEquals(plainText, decrypted, "Key length: " + key.length());
        }
    }

    @Test
    public void testSpecialCharacters() {
        String key = "xiaozhi1234567890";
        String[] testTexts = {
                "Hello World",
                "Hello world",
                "Hello, XiaoZhi!",
                "Special characters: !@#$%^&*()",
                "Digits123 mixed with text",
                "Emoji: 😀🎉🚀",
                "Empty string test",
                ""
        };

        for (String text : testTexts) {
            String encrypted = AESUtils.encrypt(key, text);
            String decrypted = AESUtils.decrypt(key, encrypted);
            assertEquals(text, decrypted, "Test text: " + text);
        }
    }

    @Test
    public void testCrossLanguageCompatibility() {
        // These are encryption results generated by the Python version, used to test cross-language compatibility
        String key = "xiaozhi1234567890";
        String plainText = "Hello, XiaoZhi!";

        // Encryption result generated by the Python version (obtain it by running the Python tests)
        // String pythonEncrypted = "encrypted result obtained from the Python tests";
        // String decrypted = AESUtils.decrypt(key, pythonEncrypted);
        // assertEquals(plainText, decrypted, "Java should be able to decrypt results encrypted by Python");

        // Generate a Java encryption result for the Python tests
        String javaEncrypted = AESUtils.encrypt(key, plainText);
        System.out.println("Java encryption result for the Python tests: " + javaEncrypted);
    }
}